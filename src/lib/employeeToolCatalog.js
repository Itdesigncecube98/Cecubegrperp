export function employeeToolCode(module, name) {
  const slug = name.normalize('NFKD').replace(/[\u0300-\u036f]/g, '')
    .replace(/[^a-zA-Z0-9]+/g, '_').replace(/^_+|_+$/g, '').toUpperCase();
  return `EMP_${module.toUpperCase()}_${slug}`;
}

